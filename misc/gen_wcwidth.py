"""Generates the wcwidth table used by libtsm from the Unicode Character Database.

Usage:
  misc/gen_wcwidth.py           write addons/godot_xterm/native/unicode/tsm_wcwidth.c
  misc/gen_wcwidth.py --check   exit 1 if the committed file differs from a fresh build

The data files are downloaded into --cache-dir and checked against the SHA-256 sums below.
"""

import argparse
import hashlib
import os
import sys
import tempfile
import urllib.request

UNICODE_VERSION = "16.0.0"
BASE_URL = f"https://www.unicode.org/Public/{UNICODE_VERSION}/ucd/"
DATA_FILES = {
    "EastAsianWidth.txt": "43adc76c0686a42cb370764eb8cfe2b2a45b10b855e5572a2db4a0eecce15d5b",
    "extracted/DerivedGeneralCategory.txt": "7676ab755a41ef82108460238569e60ad65c191ddafe61b36c6765ec1353f293",
    "PropList.txt": "53d614508e2a0b2305a8aa21cd60d993de9326cdf65993660dfcce4503548583",
    "emoji/emoji-data.txt": "f1365a5173eee18e1f98b240cdc492e84a25f1ce7e0c9d1094eb29c41a22696a",
}

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUTPUT = os.path.join(REPO_ROOT, "addons", "godot_xterm", "native", "unicode", "tsm_wcwidth.c")

# UAX #11: unassigned code points in these ranges default to W.
DEFAULT_WIDE = [(0x3400, 0x4DBF), (0x4E00, 0x9FFF), (0xF900, 0xFAFF), (0x20000, 0x2FFFD), (0x30000, 0x3FFFD)]

# Hangul Jamo medial vowels and final consonants join the preceding syllable.
HANGUL_JAMO_ZERO = [(0x1160, 0x11FF), (0xD7B0, 0xD7FF)]

REGIONAL_INDICATORS = (0x1F1E6, 0x1F1FF)


def fetch(cache_dir):
    paths = {}
    for name, sha256 in DATA_FILES.items():
        path = os.path.join(cache_dir, UNICODE_VERSION, name)
        if not os.path.exists(path):
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with urllib.request.urlopen(BASE_URL + name) as response:
                data = response.read()
            with open(path, "wb") as f:
                f.write(data)
        with open(path, "rb") as f:
            actual = hashlib.sha256(f.read()).hexdigest()
        if actual != sha256:
            sys.exit(f"{name}: SHA-256 {actual} does not match {sha256}")
        paths[name] = path
    return paths


def parse(path):
    """Yields (first, last, value) for each data line of a UCD property file."""
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            fields = [field.strip() for field in line.split(";")]
            if ".." in fields[0]:
                first, last = (int(cp, 16) for cp in fields[0].split(".."))
            else:
                first = last = int(fields[0], 16)
            yield first, last, fields[1]


def code_points(path, values):
    result = set()
    for first, last, value in parse(path):
        if value in values:
            result.update(range(first, last + 1))
    return result


def to_ranges(cps):
    ranges = []
    for cp in sorted(cps):
        if ranges and ranges[-1][1] == cp - 1:
            ranges[-1][1] = cp
        else:
            ranges.append([cp, cp])
    return ranges


def build_tables(paths):
    general_category = paths["extracted/DerivedGeneralCategory.txt"]
    east_asian_width = paths["EastAsianWidth.txt"]

    listed = set()
    for first, last, _ in parse(east_asian_width):
        listed.update(range(first, last + 1))
    wide = code_points(east_asian_width, {"W", "F"})
    for first, last in DEFAULT_WIDE:
        wide.update(cp for cp in range(first, last + 1) if cp not in listed)

    zero = code_points(general_category, {"Mn", "Me", "Cf", "Zl", "Zp"})
    zero -= code_points(paths["PropList.txt"], {"Prepended_Concatenation_Mark"})
    zero.discard(0x00AD)  # SOFT HYPHEN is visible when it ends a line.
    for first, last in HANGUL_JAMO_ZERO:
        zero.update(range(first, last + 1))

    # Emoji shown as emoji by default must be wide, or rows shift in programs that measure them.
    emoji = code_points(paths["emoji/emoji-data.txt"], {"Emoji_Presentation"})
    emoji -= set(range(REGIONAL_INDICATORS[0], REGIONAL_INDICATORS[1] + 1))
    narrow_emoji = sorted(emoji - wide)
    if narrow_emoji:
        sys.exit("Emoji_Presentation code points not wide: " + ", ".join(f"U+{cp:04X}" for cp in narrow_emoji))

    # Combining marks that are also W (for example U+3099) attach to the previous cell.
    wide -= zero

    return to_ranges(zero), to_ranges(wide)


def render(zero, wide):
    def table(name, ranges):
        rows = "\n".join(f"    {{0x{first:05x}, 0x{last:05x}}}," for first, last in ranges)
        return f"static const struct width_interval {name}[] = {{\n{rows}\n}};\n"

    return f"""// SPDX-FileCopyrightText: 2026 Jared Swarts
// SPDX-License-Identifier: MIT

// Generated by misc/gen_wcwidth.py from Unicode {UNICODE_VERSION}. Do not edit.
//   0: Mn, Me, Cf (except U+00AD and prepended concatenation marks), Zl, Zp,
//      Hangul Jamo medial vowels and final consonants.
//   2: East_Asian_Width W or F, and unassigned code points that default to W.
//  -1: C0 and C1 control characters.
//   1: everything else, including private use characters.

#include "wcwidth.h"

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

struct width_interval {{
    uint32_t first;
    uint32_t last;
}};

{table("ZERO_WIDTH", zero)}
{table("WIDE", wide)}
static bool in_table(const struct width_interval* table, size_t length, uint32_t cp) {{
    if (cp < table[0].first || cp > table[length - 1].last)
        return false;

    size_t low = 0;
    size_t high = length;
    while (low < high) {{
        size_t mid = low + (high - low) / 2;
        if (table[mid].last < cp)
            low = mid + 1;
        else if (table[mid].first > cp)
            high = mid;
        else
            return true;
    }}
    return false;
}}

int tsm_wcwidth(wchar_t ucs) {{
    uint32_t cp = (uint32_t)ucs;

    if (cp == 0)
        return 0;
    if (cp < 0x20 || (cp >= 0x7f && cp < 0xa0))
        return -1;
    if (cp > 0x10ffff)
        return 1;
    if (in_table(ZERO_WIDTH, sizeof(ZERO_WIDTH) / sizeof(ZERO_WIDTH[0]), cp))
        return 0;
    if (in_table(WIDE, sizeof(WIDE) / sizeof(WIDE[0]), cp))
        return 2;
    return 1;
}}
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--cache-dir", default=os.path.join(tempfile.gettempdir(), "godot-xterm-ucd"))
    args = parser.parse_args()

    source = render(*build_tables(fetch(args.cache_dir)))

    if args.check:
        with open(OUTPUT, encoding="utf-8") as f:
            if f.read() != source:
                sys.exit(f"{os.path.relpath(OUTPUT, REPO_ROOT)} is out of date; run misc/gen_wcwidth.py")
        print(f"{os.path.relpath(OUTPUT, REPO_ROOT)} matches Unicode {UNICODE_VERSION}")
        return

    os.makedirs(os.path.dirname(OUTPUT), exist_ok=True)
    with open(OUTPUT, "w", encoding="utf-8") as f:
        f.write(source)
    print(f"Wrote {os.path.relpath(OUTPUT, REPO_ROOT)}")


if __name__ == "__main__":
    main()
